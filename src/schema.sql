-- CodeREM Labs Income Management — database schema
-- All money values are stored as INTEGER minor units (cents) to avoid floating point errors.
-- All dates are ISO-8601 strings (YYYY-MM-DD), timestamps are ISO-8601 UTC.

PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  name          TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE COLLATE NOCASE,
  password_hash TEXT NOT NULL,
  is_active     INTEGER NOT NULL DEFAULT 1,
  created_by    INTEGER REFERENCES users(id),
  created_at    TEXT NOT NULL,
  last_login_at TEXT
);

CREATE TABLE IF NOT EXISTS sessions (
  sid     TEXT PRIMARY KEY,
  data    TEXT NOT NULL,
  expires INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS clients (
  id             INTEGER PRIMARY KEY AUTOINCREMENT,
  name           TEXT NOT NULL,
  contact_person TEXT,
  email          TEXT,
  phone          TEXT,
  address        TEXT,
  tax_id         TEXT,
  currency       TEXT NOT NULL DEFAULT 'LKR',
  notes          TEXT,
  created_at     TEXT NOT NULL,
  updated_at     TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS projects (
  id           INTEGER PRIMARY KEY AUTOINCREMENT,
  client_id    INTEGER NOT NULL REFERENCES clients(id),
  name         TEXT NOT NULL,
  description  TEXT,
  total_amount INTEGER NOT NULL DEFAULT 0,
  status       TEXT NOT NULL DEFAULT 'active'
               CHECK (status IN ('planned','active','on_hold','completed','cancelled')),
  start_date   TEXT,
  end_date     TEXT,
  created_at   TEXT NOT NULL,
  updated_at   TEXT NOT NULL
);

-- Expected installments (the payment plan) for a project
CREATE TABLE IF NOT EXISTS installments (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  project_id  INTEGER NOT NULL REFERENCES projects(id),
  seq         INTEGER NOT NULL,
  description TEXT NOT NULL,
  amount      INTEGER NOT NULL CHECK (amount > 0),
  due_date    TEXT,
  created_at  TEXT NOT NULL
);

-- Monthly maintenance / support contracts
CREATE TABLE IF NOT EXISTS contracts (
  id                INTEGER PRIMARY KEY AUTOINCREMENT,
  client_id         INTEGER NOT NULL REFERENCES clients(id),
  project_id        INTEGER REFERENCES projects(id),
  title             TEXT NOT NULL,
  description       TEXT,
  monthly_amount    INTEGER NOT NULL CHECK (monthly_amount > 0),
  start_date        TEXT NOT NULL,          -- first day of service
  end_date          TEXT,                   -- NULL = open ended
  invoice_day       INTEGER NOT NULL CHECK (invoice_day BETWEEN 1 AND 28),
  payment_terms     INTEGER NOT NULL DEFAULT 14,
  status            TEXT NOT NULL DEFAULT 'active'
                    CHECK (status IN ('active','paused','ended')),
  periods_issued    INTEGER NOT NULL DEFAULT 0, -- number of monthly periods already invoiced
  created_at        TEXT NOT NULL,
  updated_at        TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS invoices (
  id              INTEGER PRIMARY KEY AUTOINCREMENT,
  uid             TEXT NOT NULL UNIQUE,
  client_id       INTEGER NOT NULL REFERENCES clients(id),
  contract_id     INTEGER REFERENCES contracts(id),
  currency        TEXT NOT NULL,
  issue_date      TEXT NOT NULL,
  due_date        TEXT NOT NULL,
  total           INTEGER NOT NULL,
  notes           TEXT,
  client_snapshot TEXT NOT NULL,            -- JSON: client details at time of issue
  company_snapshot TEXT NOT NULL,           -- JSON: company details at time of issue
  content_hash    TEXT NOT NULL,            -- SHA-256 of the invoice content, printed on the PDF
  status          TEXT NOT NULL DEFAULT 'issued' CHECK (status IN ('issued','void')),
  void_reason     TEXT,
  voided_at       TEXT,
  voided_by       INTEGER REFERENCES users(id),
  created_by      INTEGER REFERENCES users(id), -- NULL = generated by the scheduler
  created_at      TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS invoice_items (
  id             INTEGER PRIMARY KEY AUTOINCREMENT,
  invoice_id     INTEGER NOT NULL REFERENCES invoices(id),
  position       INTEGER NOT NULL,
  description    TEXT NOT NULL,
  amount         INTEGER NOT NULL,
  project_id     INTEGER REFERENCES projects(id),
  installment_id INTEGER REFERENCES installments(id),
  contract_id    INTEGER REFERENCES contracts(id),
  period_start   TEXT,
  period_end     TEXT
);

CREATE TABLE IF NOT EXISTS payments (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  invoice_id    INTEGER NOT NULL REFERENCES invoices(id),
  amount        INTEGER NOT NULL,           -- negative for a reversal
  payment_date  TEXT NOT NULL,
  method        TEXT NOT NULL,
  reference     TEXT,
  notes         TEXT,
  reverses_id   INTEGER REFERENCES payments(id),
  recorded_by   INTEGER REFERENCES users(id),
  created_at    TEXT NOT NULL
);

-- Cashflow ledger: every money movement. Payments create inflow entries automatically.
CREATE TABLE IF NOT EXISTS cash_entries (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  entry_date  TEXT NOT NULL,
  direction   TEXT NOT NULL CHECK (direction IN ('in','out')),
  amount      INTEGER NOT NULL CHECK (amount > 0),
  currency    TEXT NOT NULL,
  category    TEXT NOT NULL,
  description TEXT NOT NULL,
  payment_id  INTEGER REFERENCES payments(id),
  reverses_id INTEGER REFERENCES cash_entries(id),
  recorded_by INTEGER REFERENCES users(id),
  created_at  TEXT NOT NULL
);

-- Append-only, hash-chained audit trail.
CREATE TABLE IF NOT EXISTS audit_log (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  ts          TEXT NOT NULL,
  user_id     INTEGER,
  user_label  TEXT NOT NULL,
  action      TEXT NOT NULL,
  entity      TEXT,
  entity_id   TEXT,
  details     TEXT,
  ip          TEXT,
  prev_hash   TEXT NOT NULL,
  hash        TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_projects_client   ON projects(client_id);
CREATE INDEX IF NOT EXISTS idx_installments_proj ON installments(project_id);
CREATE INDEX IF NOT EXISTS idx_contracts_client  ON contracts(client_id);
CREATE INDEX IF NOT EXISTS idx_invoices_client   ON invoices(client_id);
CREATE INDEX IF NOT EXISTS idx_items_invoice     ON invoice_items(invoice_id);
CREATE INDEX IF NOT EXISTS idx_items_installment ON invoice_items(installment_id);
CREATE INDEX IF NOT EXISTS idx_payments_invoice  ON payments(invoice_id);
CREATE INDEX IF NOT EXISTS idx_cash_date         ON cash_entries(entry_date);
CREATE INDEX IF NOT EXISTS idx_audit_entity      ON audit_log(entity, entity_id);

-- ---------------------------------------------------------------------------
-- Immutability guarantees, enforced by the database itself (not just the app)
-- ---------------------------------------------------------------------------

-- Audit log: no updates, no deletes — ever.
CREATE TRIGGER IF NOT EXISTS audit_log_no_update BEFORE UPDATE ON audit_log
BEGIN SELECT RAISE(ABORT, 'audit_log is append-only'); END;
CREATE TRIGGER IF NOT EXISTS audit_log_no_delete BEFORE DELETE ON audit_log
BEGIN SELECT RAISE(ABORT, 'audit_log is append-only'); END;

-- Invoices: never deleted; content fields can never change (only voiding is allowed).
CREATE TRIGGER IF NOT EXISTS invoices_no_delete BEFORE DELETE ON invoices
BEGIN SELECT RAISE(ABORT, 'invoices cannot be deleted; void them instead'); END;
CREATE TRIGGER IF NOT EXISTS invoices_content_locked BEFORE UPDATE ON invoices
WHEN NEW.uid IS NOT OLD.uid OR NEW.client_id IS NOT OLD.client_id OR NEW.total IS NOT OLD.total
  OR NEW.currency IS NOT OLD.currency OR NEW.issue_date IS NOT OLD.issue_date
  OR NEW.due_date IS NOT OLD.due_date OR NEW.client_snapshot IS NOT OLD.client_snapshot
  OR NEW.company_snapshot IS NOT OLD.company_snapshot OR NEW.content_hash IS NOT OLD.content_hash
  OR NEW.notes IS NOT OLD.notes OR NEW.created_at IS NOT OLD.created_at
  OR (OLD.status = 'void')
BEGIN SELECT RAISE(ABORT, 'issued invoices are immutable'); END;

CREATE TRIGGER IF NOT EXISTS invoice_items_no_update BEFORE UPDATE ON invoice_items
BEGIN SELECT RAISE(ABORT, 'invoice items are immutable'); END;
CREATE TRIGGER IF NOT EXISTS invoice_items_no_delete BEFORE DELETE ON invoice_items
BEGIN SELECT RAISE(ABORT, 'invoice items are immutable'); END;

-- Payments and cash entries: corrections are made with reversing entries, never edits.
CREATE TRIGGER IF NOT EXISTS payments_no_update BEFORE UPDATE ON payments
BEGIN SELECT RAISE(ABORT, 'payments are immutable; record a reversal instead'); END;
CREATE TRIGGER IF NOT EXISTS payments_no_delete BEFORE DELETE ON payments
BEGIN SELECT RAISE(ABORT, 'payments are immutable; record a reversal instead'); END;
CREATE TRIGGER IF NOT EXISTS cash_no_update BEFORE UPDATE ON cash_entries
BEGIN SELECT RAISE(ABORT, 'cash entries are immutable; record a reversal instead'); END;
CREATE TRIGGER IF NOT EXISTS cash_no_delete BEFORE DELETE ON cash_entries
BEGIN SELECT RAISE(ABORT, 'cash entries are immutable; record a reversal instead'); END;

-- Users are deactivated, never deleted (keeps the audit trail meaningful).
CREATE TRIGGER IF NOT EXISTS users_no_delete BEFORE DELETE ON users
BEGIN SELECT RAISE(ABORT, 'users cannot be deleted; deactivate them instead'); END;
